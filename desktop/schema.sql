-- Esta versao e voltada a prototipo escolar. As policies de demonstracao permitem
-- leitura e escrita sem login para simplificar a sincronizacao do site e Desktop.
-- Nao use dados pessoais reais ate implementar Supabase Auth e policies por usuario.

create table if not exists public.loja (
  id bigint generated by default as identity primary key,
  nome varchar(100) not null,
  dono_nome varchar(100) not null,
  cnpj varchar(20),
  endereco varchar(200) not null,
  paleta_cores varchar(50) default 'Azul Padrão',
  created_at timestamptz not null default now()
);

create table if not exists public.produto (
  id bigint generated by default as identity primary key,
  loja_id bigint not null references public.loja(id) on delete cascade,
  nome varchar(100) not null,
  preco numeric(10,2) not null check (preco >= 0),
  descricao varchar(255),
  clima varchar(20) default 'Todos',
  apimentado boolean not null default false,
  gluten boolean not null default true,
  lactose boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.acessifood_state (
  id text primary key default 'global' check (id = 'global'),
  state_json jsonb not null,
  revision bigint not null default 1,
  updated_at timestamptz not null default now()
);

create index if not exists produto_loja_id_idx on public.produto(loja_id);

alter table public.loja enable row level security;
alter table public.produto enable row level security;
alter table public.acessifood_state enable row level security;

-- Permissoes para a versao demonstrativa sem tela de login.
-- Restrinja estas policies antes de publicar para clientes reais.
drop policy if exists "demo_loja_publica" on public.loja;
create policy "demo_loja_publica" on public.loja for all to anon, authenticated using (true) with check (true);

drop policy if exists "demo_produto_publico" on public.produto;
create policy "demo_produto_publico" on public.produto for all to anon, authenticated using (true) with check (true);

drop policy if exists "demo_estado_compartilhado" on public.acessifood_state;
create policy "demo_estado_compartilhado" on public.acessifood_state for all to anon, authenticated using (true) with check (true);

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.loja, public.produto, public.acessifood_state to anon, authenticated;
grant usage, select on sequence public.loja_id_seq, public.produto_id_seq to anon, authenticated;

create or replace function public.acessifood_state_save(p_state jsonb)
returns table(revision bigint, updated_at timestamptz)
language plpgsql
security invoker
set search_path = public
as $$
begin
  if jsonb_typeof(p_state) <> 'object'
     or jsonb_typeof(p_state -> 'products') is distinct from 'array'
     or jsonb_typeof(p_state -> 'orders') is distinct from 'array' then
    raise exception 'Estado invalido do AcessiFood.';
  end if;

  insert into public.acessifood_state as current_state (id, state_json, revision, updated_at)
  values ('global', p_state, 1, now())
  on conflict (id) do update
    set state_json = excluded.state_json,
        revision = current_state.revision + 1,
        updated_at = now();

  return query
    select saved.revision, saved.updated_at
    from public.acessifood_state as saved
    where saved.id = 'global';
end;
$$;

grant execute on function public.acessifood_state_save(jsonb) to anon, authenticated;
